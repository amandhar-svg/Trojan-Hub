#!/usr/bin/env python3
"""Turn the split Trojan Assist prototype (/home/user/ta-src) into files Trojan Hub can load with <script src>.

    python3 build_ta.py [SRC_DIR] [OUT_DIR]      # defaults: /home/user/ta-src  ./js/ta

Writes OUT_DIR/app.js (all TA modules, with three small main.js patches) and OUT_DIR/blob-{kb,soc,acts,meta}.js,
which register the data blocks as window.TA_BLOBS['ta-kb'|'ta-soc'|'ta-acts'|'ta-meta'] (the same ids the
original <script type="application/..."> tags used). The bundled Anthropic SDK (sdk.html, 376 KB) is NOT
copied: the artifact build uses window.claude.use('sample') instead (ai-sample.js).
"""
import json, os, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else '/home/user/ta-src'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'js/ta'
os.makedirs(OUT, exist_ok=True)

app = open(os.path.join(SRC, 'app.html'), encoding='utf-8').read().rstrip()
assert app.startswith('<script>') and app.endswith('</html>'), 'unexpected app.html framing'
app = app[len('<script>'):app.rindex('</script>')]

PATCHES = [
    # 1) data blocks may come from js/ta/blob-*.js instead of inline <script id="ta-..."> tags
    ("function text(id) { var el = document.getElementById(id); return el ? el.textContent.trim() : ''; }",
     "function text(id) { var el = document.getElementById(id); if (el) return el.textContent.trim(); var b = window.TA_BLOBS && window.TA_BLOBS[id]; return b ? String(b).trim() : ''; }"),
    # 2) boot(opts): the knowledge base can arrive later (opts.kbLater) and be started with TA.Search.init(b64)
    ("  function boot() {", "  function boot(opts) {\n    opts = opts || {};"),
    ("if (kbB64) TA.Search.init(kbB64); else { TA.Search.failed = 'Knowledge base missing'; }",
     "if (kbB64) { TA.Search.init(kbB64); if (window.TA_BLOBS) delete window.TA_BLOBS['ta-kb']; } else if (!opts.kbLater) { TA.Search.failed = 'Knowledge base missing'; }"),
    # 3) no auto-boot: Trojan Hub calls TA.boot() (before TH.boot()) so TA.State is ready for My Day/Wallet
    ("  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot); else boot();",
     "  TA.boot = boot;\n  if (!window.TA_MANUAL_BOOT) { if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot); else boot(); }"),
]
for old, new in PATCHES:
    assert app.count(old) == 1, 'patch anchor not found exactly once: ' + old[:60]
    app = app.replace(old, new)
open(os.path.join(OUT, 'app.js'), 'w', encoding='utf-8').write('/* Trojan Assist engine (generated by build_ta.py from ta-src/app.html; do not edit by hand) */\n' + app + '\n')

for name in ('kb', 'soc', 'acts', 'meta'):
    raw = open(os.path.join(SRC, name + '.html'), encoding='utf-8').read()
    body = raw[raw.index('>') + 1:raw.rindex('</script>')].strip()
    open(os.path.join(OUT, 'blob-%s.js' % name), 'w', encoding='utf-8').write(
        "(window.TA_BLOBS = window.TA_BLOBS || {})['ta-%s'] = %s;\n" % (name, json.dumps(body)))
for f in sorted(os.listdir(OUT)):
    print('%-14s %8.1f KB' % (f, os.path.getsize(os.path.join(OUT, f)) / 1024))
