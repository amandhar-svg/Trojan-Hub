#!/usr/bin/env node
/* Build the deployable Trojan Hub site with Ask Tommy's AI on the Claude API (Netlify Function).
 *
 *   node scripts/build-netlify.cjs [--project /home/user/trojan-hub-v4] [--out ./netlify-site]
 *
 * 1. builds the app (python3 <project>/scripts/build.py) — adds js/ta/ai-api.js if the build doesn't have it yet
 * 2. opens the built app in a headless browser and captures the exact command catalogue Tommy sends to its translator
 * 3. writes <out>/: site/index.html, netlify/functions/tommy.mjs + tommy-prompt.mjs (generated), netlify.toml,
 *    package.json, package-lock.json, README.md, .gitignore — ready to push to GitHub and connect to Netlify. */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { chromium } = require('playwright');

const SRC = path.resolve(__dirname, '..');
const argv = process.argv.slice(2);
const opt = (name, dflt) => { const i = argv.indexOf(name); return i >= 0 && argv[i + 1] ? path.resolve(argv[i + 1]) : dflt; };
const PROJECT = opt('--project', fs.existsSync(path.join(SRC, 'template.html')) ? SRC : '/home/user/trojan-hub-v4');
const OUT = opt('--out', path.join(SRC, 'netlify-site'));
const TMP = fs.mkdtempSync(path.join(require('os').tmpdir(), 'th-netlify-'));

function readFirst(...files) { for (const f of files) if (fs.existsSync(f)) return fs.readFileSync(f, 'utf8'); throw new Error('missing: ' + files.join(' or ')); }

(async () => {
  // 1. build the app
  const built = path.join(TMP, 'th.html');
  execFileSync('python3', [path.join(PROJECT, 'scripts', 'build.py'), built], { stdio: 'inherit' });
  let html = fs.readFileSync(built, 'utf8');
  if (!html.includes('/* js/ta/ai-api.js */')) {
    const api = readFirst(path.join(PROJECT, 'js', 'ta', 'ai-api.js'), path.join(SRC, 'js', 'ta', 'ai-api.js'));
    if (/<\/script/i.test(api)) throw new Error('ai-api.js contains a closing script tag');
    const at = html.indexOf('/* js/ta/ai-sample.js */');
    const end = at < 0 ? -1 : html.indexOf('</script>', at);
    if (end < 0) throw new Error('could not find the ai-sample.js block in the build');
    html = html.slice(0, end + 9) + '<script>' + api + '</script>' + html.slice(end + 9);
    fs.writeFileSync(built, html);
    console.log('added js/ta/ai-api.js to the build');
  }

  // 2. capture the translator's catalogue exactly as script.js builds it
  const rulesSrc = fs.readFileSync(path.join(PROJECT, 'js', 'ta', 'ai-sample.js'), 'utf8');
  const m = /var RULES = (\[[\s\S]*?\])\.join\('\\n'\);/.exec(rulesSrc);
  if (!m) throw new Error('RULES not found in js/ta/ai-sample.js');
  const RULES = new Function('return ' + m[1])().join('\n');

  const browser = await chromium.launch();
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('file://' + built);
  await page.waitForFunction(() => document.documentElement.getAttribute('data-kb') === 'ready' && window.TA && TA.Script && TA.Script.catalog, null, { timeout: 120000 });
  const cap = await page.evaluate(async () => {
    const AI = TA.AI, t0 = AI.translate, e0 = AI.enabled;
    let got = null;
    AI.enabled = () => true;
    AI.translate = async (text, c) => { got = c; return null; };
    try { await TA.Script.handle('zxqv blorptastic flimflam wobble quux'); } finally { AI.translate = t0; AI.enabled = e0; }
    const cmds = {};
    for (const k of Object.keys(TA.Script.cmds)) cmds[k] = (TA.Script.cmds[k].args || []).map(String);
    return { commands: got && got.commands, actions: got && got.actions, cmds };
  });
  await browser.close();
  if (errors.length) throw new Error('page errors while capturing the catalogue: ' + errors.join(' | '));
  if (!cap.commands || !cap.actions) throw new Error('the translator was not reached; could not capture the catalogue');
  for (const line of ['do {action, request}', 'ask {q}', 'none {}']) if (!cap.commands.includes(line)) throw new Error('catalogue is missing: ' + line);

  const COMMANDS = Object.assign({}, cap.cmds, { do: ['action', 'request'], ask: ['q'] });
  const SYSTEM = RULES + '\n\nCOMMANDS\n' + cap.commands + '\n\nACTIONS (id = what it does)\n' + cap.actions;

  // 3. write the site
  fs.rmSync(OUT, { recursive: true, force: true });
  const w = (rel, body) => { const p = path.join(OUT, rel); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, body); };
  w('site/index.html', html);
  w('netlify/functions/tommy.mjs', fs.readFileSync(path.join(SRC, 'netlify', 'functions', 'tommy.mjs'), 'utf8'));
  w('netlify/functions/tommy-prompt.mjs',
    '// GENERATED by scripts/build-netlify.cjs from the app\'s own command catalogue. Do not edit by hand; rebuild instead.\n' +
    'export const SYSTEM = ' + JSON.stringify(SYSTEM) + ';\n' +
    'export const COMMANDS = ' + JSON.stringify(COMMANDS, null, 1) + ';\n');
  for (const f of ['netlify.toml', 'package.json', 'package-lock.json', 'README.md']) w(f, fs.readFileSync(path.join(SRC, 'netlify-files', f), 'utf8'));
  w('.gitignore', 'node_modules/\n.netlify/\n');
  fs.rmSync(TMP, { recursive: true, force: true });

  console.log('wrote', OUT);
  console.log('  site/index.html', (Buffer.byteLength(html) / 1e6).toFixed(2), 'MB');
  console.log('  translator prompt', SYSTEM.length, 'chars (~' + Math.round(SYSTEM.length / 3.6) + ' tokens),', Object.keys(COMMANDS).length, 'commands');
})().catch((e) => { console.error('build-netlify failed:', e.message); process.exit(1); });
